#!/usr/bin/env node
/**
 * Put a packaged desktop build where the installed copies will look for it:
 * this build's feed (frontend/scripts/feed.js), GitHub Releases or a sync
 * service's bucket.
 *
 * `electron-builder` can upload as it builds (`--publish always`), and this
 * does not use that. The reason is the ordering: a manifest naming a file that
 * is not there yet is a broken update for everybody who asks in between, and
 * the built-in publisher offers no way to say which file goes last.
 *
 *   node scripts/publish-update.js            # upload
 *   node scripts/publish-update.js --dry-run  # say what would be uploaded
 *
 * A bucket needs `wrangler login` done once; GitHub needs GITHUB_TOKEN.
 */

const { existsSync, mkdirSync, readFileSync, writeFileSync } = require('fs');
const { join, resolve } = require('path');

const { publish, addressFor, checkBuiltConfig } = require('../../scripts/publish');
const { releaseTarget } = require('../../scripts/feed');

const APP = resolve(__dirname, '..');
const DIST = join(APP, 'dist');

const dryRun = process.argv.includes('--dry-run');

const die = message => {
  console.error(`\n  ${message}\n`);
  process.exit(1);
};

/**
 * The fields this needs out of `latest.yml`.
 *
 * A YAML parser for a file with three keys in it, generated by a program, is
 * a dependency bought for nothing. If electron-builder ever changes the shape,
 * the checks below fail loudly rather than uploading something unchecked.
 */
const readManifest = text => {
  const version = /^version:\s*(.+)$/m.exec(text);
  const files = [...text.matchAll(/^\s*-?\s*url:\s*(.+)$/gm)].map(match => match[1].trim());

  return { version: version ? version[1].trim() : null, files };
};

const manifestPath = join(DIST, 'latest.yml');

if (!existsSync(manifestPath)) {
  die('No dist/latest.yml. Run `npm run electron:make` first.');
}

const text = readFileSync(manifestPath, 'utf8');
const manifest = readManifest(text);
const version = require(join(APP, 'package.json')).version;

if (manifest.version !== version) {
  // The failure this catches: a build that did not rerun, so the manifest
  // offers a version that was never packaged. Every installed copy would try
  // to download a file that does not exist, for as long as it took anybody to
  // notice.
  die(`dist/latest.yml offers ${manifest.version}, but this app is ${version}. Rebuild.`);
}

if (manifest.files.length === 0) {
  die('dist/latest.yml names no files, which cannot be right.');
}

/**
 * What the packaged app was built to ask, read out of the build rather than
 * assumed: the feed baked into `app-update.yml`, and the web code's config.js.
 * An installer published to a feed it does not read is installed once and
 * never updated again.
 */
const target = releaseTarget();
const baked = join(DIST, 'win-unpacked', 'resources', 'app-update.yml');
if (!existsSync(baked)) {
  die('No dist/win-unpacked/resources/app-update.yml. Run `npm run electron:make` first.');
}
const bakedUrl = /^url:\s*(.+)$/m.exec(readFileSync(baked, 'utf8'));
if (!bakedUrl || bakedUrl[1].trim() !== target.url) {
  die(`The build updates from ${bakedUrl ? bakedUrl[1].trim() : 'nowhere'}, not from ${target.url}. Rebuild.`);
}
const pointsAt = checkBuiltConfig(readFileSync(join(APP, 'app', 'config.js'), 'utf8'), 'The desktop build’s config.js', die);

/** Everything the manifest promises, plus the blockmaps that make deltas work. */
const files = [];

for (const name of manifest.files) {
  const file = join(DIST, name);
  if (!existsSync(file)) {
    die(`dist/latest.yml names ${name}, which is not in dist. Rebuild.`);
  }

  files.push({ name, path: file, contentType: 'application/octet-stream' });

  if (existsSync(`${file}.blockmap`)) {
    files.push({ name: `${name}.blockmap`, path: `${file}.blockmap`, contentType: 'application/octet-stream' });
  }
}

/**
 * The manifest as published: on GitHub each file is named by its full address
 * in the release that holds it, since the feed release holds manifests only.
 * electron-updater finds the previous version's blockmap by putting the old
 * version where the new one is in that address, and the release's tag carries
 * the version too, so the delta download still finds it.
 */
const published = text.replace(/^(\s*-?\s*(?:url|path):\s*)(.+)$/gm, (_, key, name) => key + addressFor('desktop', version, name.trim(), target));
const outDir = join(DIST, 'feed');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'latest.yml'), published);

console.info(`\n  Windows ${version}; ${pointsAt}`);

publish({
  kind: 'desktop',
  version,
  files,
  manifest: { name: 'latest.yml', path: join(outDir, 'latest.yml'), contentType: 'text/yaml' },
  dryRun,
  die
}).then(() => {
  if (!dryRun) {
    console.info(`\n  ${version} is live. Installed copies will find it within a few hours, or on their next start.\n`);
  }
});
