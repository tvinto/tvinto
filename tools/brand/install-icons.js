// Puts the mark from brand/svg/ into the apps: Android's launcher icons,
// adaptive layers, TV banner and splash screens; the desktop's icon and
// splash; the web favicon. Run after build-brand.js.
//   cd tools/brand && npm install && node build-brand.js && node install-icons.js
const fs = require('fs');
const path = require('path');
const { Resvg } = require('@resvg/resvg-js');
const pngToIco = require('png-to-ico').default ?? require('png-to-ico');

const REPO = path.resolve(__dirname, '../..');
const SVG = path.join(REPO, 'brand', 'svg');
const RES = path.join(REPO, 'frontend/android/app/src/main/res');
const NIGHT = '#091426';

const read = name => fs.readFileSync(path.join(SVG, name), 'utf8');
const inner = svg => svg.replace(/^<svg[^>]*>|<\/svg>$/g, '');
const png = (svg, width, height = width) => new Resvg(svg, { fitTo: { mode: 'width', value: width } }).render().asPng();
const write = (file, data) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, data);
};

const icon = read('tvinto-icon.svg');
const background = inner(read('android-adaptive-background.svg')); // 108 box
const foreground = inner(read('android-adaptive-foreground.svg')); // 512 box
const monochrome = inner(read('android-adaptive-monochrome.svg')); // 512 box
const banner = read('tvinto-tv-banner.svg');

// ---- Android launcher icons -------------------------------------------------
// Adaptive layers are 108 dp; the legacy square icon 48 dp (Android 7, before
// adaptive icons), drawn with the rim as on the desktop; the round one is the
// adaptive icon under a circle, for launchers that ask for it by name.
const densities = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
const layer = body => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">${body}</svg>`;
const fgIn108 = `<g transform="scale(${108 / 512})">${foreground}</g>`;
const monoIn108 = `<g transform="scale(${108 / 512})">${monochrome}</g>`;
const round = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72"><defs><clipPath id="c"><circle cx="54" cy="54" r="36"/></clipPath></defs><g clip-path="url(#c)">${background}${fgIn108}</g></svg>`;
for (const [name, scale] of Object.entries(densities)) {
  const dir = path.join(RES, `mipmap-${name}`);
  write(path.join(dir, 'ic_launcher.png'), png(icon, Math.round(48 * scale)));
  write(path.join(dir, 'ic_launcher_round.png'), png(round, Math.round(48 * scale)));
  write(path.join(dir, 'ic_launcher_background.png'), png(layer(background), Math.round(108 * scale)));
  write(path.join(dir, 'ic_launcher_foreground.png'), png(layer(fgIn108), Math.round(108 * scale)));
  write(path.join(dir, 'ic_launcher_monochrome.png'), png(layer(monoIn108), Math.round(108 * scale)));
}
const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<!-- Tvinto's mark as Android's adaptive icon: the navy tile lit from below,
     the i with its play arrow, and the arrow-less white for themed icons.
     Generated by tools/brand/install-icons.js. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome"/>
</adaptive-icon>
`;
write(path.join(RES, 'mipmap-anydpi-v26/ic_launcher.xml'), adaptive);
write(path.join(RES, 'mipmap-anydpi-v26/ic_launcher_round.xml'), adaptive);

// ---- Android TV banner: 160 x 90 dp ----------------------------------------
write(path.join(RES, 'drawable-xhdpi/tv_banner.png'), png(banner, 320));
write(path.join(RES, 'drawable-xxxhdpi/tv_banner.png'), png(banner, 640));

// ---- Splash screens: the mark, centred on the night ------------------------
function splash(width, height) {
  const side = Math.round(Math.min(width, height) * 0.22);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">` +
    `<rect width="${width}" height="${height}" fill="${NIGHT}"/>` +
    `<g transform="translate(${(width - side) / 2} ${(height - side) / 2}) scale(${side / 512})">${inner(icon)}</g></svg>`;
}
const splashes = {
  'drawable/splash.png': [480, 320],
  'drawable-land-mdpi/splash.png': [480, 320], 'drawable-land-hdpi/splash.png': [800, 480],
  'drawable-land-xhdpi/splash.png': [1280, 720], 'drawable-land-xxhdpi/splash.png': [1600, 960],
  'drawable-land-xxxhdpi/splash.png': [1920, 1280],
  'drawable-port-mdpi/splash.png': [320, 480], 'drawable-port-hdpi/splash.png': [480, 800],
  'drawable-port-xhdpi/splash.png': [720, 1280], 'drawable-port-xxhdpi/splash.png': [960, 1600],
  'drawable-port-xxxhdpi/splash.png': [1280, 1920]
};
for (const [file, [w, h]] of Object.entries(splashes)) {
  write(path.join(RES, file), png(splash(w, h), w));
}

// ---- Desktop and web --------------------------------------------------------
(async () => {
  const sizes = s => s.map(size => png(icon, size));
  write(path.join(REPO, 'frontend/electron/assets/appIcon.ico'), await pngToIco(sizes([16, 24, 32, 48, 64, 128, 256])));
  write(path.join(REPO, 'frontend/electron/assets/appIcon.png'), png(icon, 512));
  write(path.join(REPO, 'frontend/electron/assets/splash.png'), png(splash(480, 800), 480));
  write(path.join(REPO, 'frontend/src/favicon.ico'), await pngToIco(sizes([16, 32, 48])));
  console.log('icons installed');
})();
