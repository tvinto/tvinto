import { Env } from './d1';
import { HttpError } from './http';
import { UpdateBucket } from './updates';

/**
 * The page a person goes to in order to install one of these apps.
 *
 * The apps update themselves -- that is what `/updates/` is for -- but neither
 * of them can install itself the first time, and until now the answer to "how
 * do I put this on the television" was a file copied off this machine. So this
 * is the other half of the same bucket: the same objects, described rather
 * than served, plus two short paths that redirect to whichever file is current.
 *
 * **Nothing here is written down twice.** The version, the file name, the size
 * and the date all come from the manifests and the objects themselves, so a
 * release that forgets to update this page is not possible -- there is nothing
 * on it to forget. That matters more than it sounds: a download page that has
 * gone stale offers an old build to somebody who believes it is the new one,
 * and they have no way of telling.
 *
 * The short paths exist for the television. It is sideloaded with the
 * Downloader app, where a URL is typed a character at a time with a remote
 * control, so `/a` fetches the APK itself rather than a page with a link on it
 * -- one fewer screen to navigate with arrow keys, and no page to render.
 */

/** electron-builder's, and what the desktop app already asks for. */
const DESKTOP_MANIFEST = 'latest.yml';

/**
 * The APK's, written by `frontend/scripts/publish-apk.js`.
 *
 * Not `android-latest.json`, which is the *web bundle's* and is read by the
 * running app. This one is read by nothing but this page: an installed app
 * replaces its bundle over the air and never needs a new APK unless native
 * code changed, which is a thing a person decides.
 */
const ANDROID_MANIFEST = 'android-apk.json';

/** One thing that can be downloaded, as the page prints it. */
interface Download {
  file: string;
  version: string;
  size: number;
  uploaded: Date;
}

const readText = async (bucket: UpdateBucket, name: string): Promise<string | null> => {
  const object = await bucket.get(name);
  return object && object.body ? new Response(object.body).text() : null;
};

/**
 * A manifest, and then the file it names, which must actually be there.
 *
 * A manifest is uploaded last precisely so that it never names a file that has
 * not arrived -- but "never" is a property of the publishing script, and this
 * page is where somebody would find out that it had failed. Answering `null`
 * shows the other download rather than a link that 404s.
 */
const describe = async (
  bucket: UpdateBucket,
  found: { version: string; file: string } | null
): Promise<Download | null> => {
  if (!found) {
    return null;
  }

  const head = await bucket.head(found.file);

  return head
    ? { ...found, size: head.size, uploaded: head.uploaded }
    : null;
};

/**
 * The version and the first file out of `latest.yml`.
 *
 * The same two lines `publish-update.js` reads at the other end, and for the
 * same reason: a YAML parser for a file with three keys in it, generated by a
 * program, is a dependency bought for nothing.
 */
const desktopManifest = (text: string): { version: string; file: string } | null => {
  const version = /^version:\s*(.+)$/m.exec(text);
  const file = /^\s*-?\s*url:\s*(.+)$/m.exec(text);

  return version && file ? { version: version[1].trim(), file: file[1].trim() } : null;
};

const androidManifest = (text: string): { version: string; file: string } | null => {
  try {
    const parsed = JSON.parse(text) as { version?: unknown; file?: unknown };

    return typeof parsed.version === 'string' && typeof parsed.file === 'string'
      ? { version: parsed.version, file: parsed.file }
      : null;
  } catch {
    return null;
  }
};

const desktop = async (bucket: UpdateBucket): Promise<Download | null> => {
  const text = await readText(bucket, DESKTOP_MANIFEST);
  return describe(bucket, text ? desktopManifest(text) : null);
};

const android = async (bucket: UpdateBucket): Promise<Download | null> => {
  const text = await readText(bucket, ANDROID_MANIFEST);
  return describe(bucket, text ? androidManifest(text) : null);
};

/**
 * The project's releases, for a service with no bucket of its own -- which is
 * every one somebody runs for themselves. Its apps update from GitHub
 * (frontend/scripts/feed.js), so its download links go there too.
 */
const RELEASES = 'https://github.com/tvinto/tvinto/releases';
const FEED = `${RELEASES}/download/feed`;

/**
 * A manifest out of the project's feed, and the file it names, by its full address.
 *
 * `feed` is a stand-in's address in a test or a local preview of the website;
 * the address is checked against the real releases all the same. The website's
 * `/android` and `/windows` (functions/) use this too.
 */
export const fromFeed = async (which: 'android' | 'desktop', feed = FEED): Promise<string | null> => {
  const response = await fetch(`${feed}/${which === 'android' ? ANDROID_MANIFEST : DESKTOP_MANIFEST}`, {
    // Cloudflare's cache: a minute, like the redirect itself. Ignored elsewhere.
    cf: { cacheTtl: 60, cacheEverything: true }
  } as RequestInit);
  if (!response.ok) {
    return null;
  }
  const text = await response.text();
  const found = which === 'android' ? androidManifest(text) : desktopManifest(text);
  return found && found.file.startsWith(`${RELEASES}/download/`) ? found.file : null;
};

/**
 * The website's `/android` and `/windows`: the current file, or the releases
 * page when the feed cannot be read, so the address a Downloader code points at
 * never answers with an error.
 */
export const websiteDownload = async (which: 'android' | 'desktop', feed?: string): Promise<Response> => {
  const found = await fromFeed(which, feed || FEED).catch(() => null);
  return redirect(found ?? RELEASES);
};

const redirect = (location: string): Response =>
  new Response(null, {
    status: 302,
    headers: {
      Location: location,
      // The same minute the manifests get. This address means "whichever is
      // current", and a cache holding it for longer would answer with a
      // version that no longer is.
      'Cache-Control': 'public, max-age=60, must-revalidate'
    }
  });

const MONTHS = [
  'January',
  'February',
  'March',
  'April',
  'May',
  'June',
  'July',
  'August',
  'September',
  'October',
  'November',
  'December'
];

/**
 * A date somebody reads, spelled out rather than in digits.
 *
 * `07/09/2026` means two different days depending on where the reader is, and
 * this page is the one place in the system a person and a machine look at the
 * same fact.
 *
 * It is UTC, because a Worker has no other clock. Something published late in
 * a European evening therefore shows yesterday's date, which is right and
 * looks wrong. The day is here to tell an old build from a new one, and for
 * that it does not matter which side of midnight it fell.
 */
const on = (date: Date): string =>
  `${date.getUTCDate()} ${MONTHS[date.getUTCMonth()]} ${date.getUTCFullYear()}`;

const megabytes = (bytes: number): string => `${(bytes / 1048576).toFixed(0)} MB`;

const escape = (text: string): string =>
  text.replace(/[&<>"]/g, character => {
    switch (character) {
      case '&':
        return '&amp;';
      case '<':
        return '&lt;';
      case '>':
        return '&gt;';
      default:
        return '&quot;';
    }
  });

const card = (
  title: string,
  short: string,
  download: Download | null,
  note: string,
  missing: string
): string => {
  if (!download) {
    return `    <section class="card missing">
      <h2>${escape(title)}</h2>
      <p>${escape(missing)}</p>
    </section>`;
  }

  return `    <section class="card">
      <h2>${escape(title)}</h2>
      <p class="what">Version ${escape(download.version)} &middot; ${megabytes(download.size)} &middot; ${on(download.uploaded)}</p>
      <p><a class="get" href="/updates/${encodeURIComponent(download.file)}">Download</a></p>
      <p class="note">${escape(note)}</p>
      <p class="short">Or type <code>${escape(short)}</code></p>
    </section>`;
};

