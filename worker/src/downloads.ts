/**
 * `GET /downloads`.
 *
 * Cached for a minute, like the manifests it is made of: it is the same
 * question in a different shape, and an answer held any longer would offer
 * yesterday's build to the one person who came here to get today's.
 */
export const downloadsPage = async (request: Request, env: Env): Promise<Response> => {
  const bucket = env.UPDATES;
  if (!bucket) {
    return redirect(`${RELEASES}/latest`);
  }
  const [apk, exe] = await Promise.all([android(bucket), desktop(bucket)]);
  const host = new URL(request.url).host;

  return new Response(page(host, apk, exe), {
    headers: {
      'Content-Type': 'text/html; charset=utf-8',
      'Cache-Control': 'public, max-age=60, must-revalidate'
    }
  });
};

/**
 * `GET /a` and `GET /w` -- the current APK and the current installer.
 *
 * A redirect rather than the bytes, so that what arrives is the versioned name
 * out of `/updates/`. The Downloader app names the file it saved after the
 * address it ended at, and `xtream-1.0.1.apk` on a television's storage is a
 * fact somebody can check months later; `a` is not.
 */
export const latestDownload = async (env: Env, which: 'android' | 'desktop'): Promise<Response> => {
  const bucket = env.UPDATES;
  const found = bucket
    ? await (which === 'android' ? android(bucket) : desktop(bucket)).then(download =>
        download ? `/updates/${encodeURIComponent(download.file)}` : null
      )
    : await fromFeed(which);

  if (!found) {
    throw new HttpError('Nothing has been published for that yet', 404);
  }

  return redirect(found);
};
